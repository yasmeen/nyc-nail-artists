# Builds data.js for the three direction drafts from test.csv, geo.json and photos/manifest.json.
import csv, json, math, re, os
R = os.path.dirname(os.path.abspath(__file__)) + '/..'
geo = json.load(open(R + '/geo.json'))
man = json.load(open(R + '/photos/manifest.json'))
book = json.load(open(R + '/booking.json'))
USQ = (40.7359, -73.9906)
def walk(ll):
    if not ll: return None
    dy = (ll[0] - USQ[0]) * 111320; dx = (ll[1] - USQ[1]) * 111320 * math.cos(math.radians(USQ[0]))
    a = math.radians(29); u = dx * math.cos(a) - dy * math.sin(a); v = dx * math.sin(a) + dy * math.cos(a)
    return round((abs(u) + abs(v)) / 80.5)
def first(s):
    m = re.search(r'\$(\d+)', s or ''); return int(m.group(1)) if m else None
rows = list(csv.DictReader(open(R + '/test.csv')))
out = []
for r in rows:
    n = r['Name']; hard = first(r['Hard gel price']); base = first(r['Base gel price'])
    # Only explicit simple-art add-ons count (the app's `Art add-on $` column isn't in test.csv)
    art = {'Gold Room Nails': 15, 'The Paint Nail (Aurora, Cristina)': 30}.get(n)
    rating = re.match(r'\s*\w*\s*([\d.]+)\s*\((\d+)\)', r['Rating'] or '')
    tech = r['Services (hard gel/Japanese/Russian etc)']
    out.append(dict(name=n, ig=r['Instagram'], type=r['Type (solo/studio/salon)'], hood=r['Neighborhood'], addr=r['Address'],
        platform=r['Booking platform'] or ('DM' if 'DM' in r['Booking URL'] else ('Phone' if 'phone' in r['Booking URL'] else '')),
        tech=tech, mani=hard or base, artFrom=art, artText=r['Art price'], styles=r['Styles/art notes'], rating=float(rating.group(1)) if rating else None,
        reviews=int(rating.group(2)) if rating else None, notes=r['Notes'] if 'per user' not in r['Notes'] and r['Notes'] != 'unchecked' else '',
        ll=geo.get(n), walk=walk(geo.get(n)), checkable=n in book,
        photos=[dict(src='../' + p['file'], desc=p['desc']) for p in man.get(n, {}).get('photos', [])]))
# Places that have saved photos but aren't in the sample CSV: photos and pin only, no prices.
for n, v in man.items():
    if any(o['name'] == n for o in out): continue
    out.append(dict(name=n, ig='@' + v['handle'], type='', hood='', addr='', platform='', tech='', mani=None, artFrom=None,
        artText='', styles='', rating=None, reviews=None, notes='', ll=geo.get(n), walk=walk(geo.get(n)), checkable=False, sampleOnly=True,
        photos=[dict(src='../' + p['file'], desc=p['desc']) for p in v['photos']]))
open('data.js', 'w').write('// Generated by build_data.py from test.csv, geo.json and photos/manifest.json\nwindow.PLACES = ' + json.dumps(out, indent=1) + ';\n')
for o in out: print(o['name'], o['mani'], o['artFrom'], o['walk'], len(o['photos']), o['checkable'])
